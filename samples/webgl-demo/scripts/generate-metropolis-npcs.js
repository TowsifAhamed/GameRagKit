#!/usr/bin/env node
// Generates the metropolis demo's archetype roster: a small, bounded set of real
// GameRagKit NPC YAML configs (one per profession), each backing potentially hundreds of
// ambient crowd figures in metropolis.html. This is the "cluster" pattern -- the crowd can
// scale to any size in the browser, but the number of real backend NpcAgents (and therefore
// LLM calls, embeddings, and server memory) stays fixed at the archetype count, because
// every crowd figure of a given profession shares that one archetype's NpcAgent instead of
// each getting its own. Run: node generate-metropolis-npcs.js
"use strict";

const fs = require("fs");
const path = require("path");

const ARCHETYPES = [
  { role: "street food vendor", traits: "cheerful, always trying to get you to try today's special" },
  { role: "taxi dispatcher", traits: "no-nonsense, talks fast, knows every shortcut in the city" },
  { role: "newsstand owner", traits: "opinionated about current events, loves a good debate" },
  { role: "office worker on a lunch break", traits: "tired, a little sarcastic, checking the time a lot" },
  { role: "street musician", traits: "laid-back, philosophical, plays for tips" },
  { role: "delivery courier", traits: "always in a hurry but friendly if you catch them" },
  { role: "barista", traits: "warm, remembers regulars' orders, makes small talk easily" },
  { role: "security guard", traits: "watchful, formal, takes the job seriously" },
  { role: "tourist", traits: "excited, a little lost, full of questions about the city" },
  { role: "shop owner", traits: "proud of their storefront, chatty with customers" },
  { role: "city maintenance worker", traits: "practical, complains good-naturedly about the job" },
  { role: "bike courier", traits: "energetic, breathless, always moving" },
  { role: "retired teacher out for a walk", traits: "patient, likes to share little life lessons" },
  { role: "food truck chef", traits: "passionate about their recipes, boisterous" }
];

const OUTPUT_DIR = path.join(__dirname, "..", "metropolis-npcs");

function slugify(text) {
  return text.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
}

function generate() {
  fs.mkdirSync(OUTPUT_DIR, { recursive: true });

  const roster = [];
  for (const archetype of ARCHETYPES) {
    const id = slugify(archetype.role);

    // No name of its own -- every crowd figure using this archetype introduces itself
    // differently, since the same backend NPC is standing in for many different people at
    // once. The prompt makes that explicit so the model doesn't invent one fixed name.
    const yaml = `persona:
  id: ${id}
  system_prompt: >
    You are a ${archetype.role} in a bustling modern city, speaking with a passerby who
    just walked up to you on the street. You are ${archetype.traits}. You represent many
    different ${archetype.role}s across the city, not one single named person -- if asked
    your name, give a different plausible first name each time rather than a fixed one.
    Keep your responses short and conversational, like a real passerby the player just
    struck up a conversation with -- a sentence or two, not a speech.
  style: brief, conversational, in character as a ${archetype.role}

providers:
  routing:
    mode: local_only
  local:
    engine: ollama
    chat_model: llama3.2:3b-instruct-q4_K_M
    embed_model: nomic-embed-text
    endpoint: http://127.0.0.1:11434
`;

    fs.writeFileSync(path.join(OUTPUT_DIR, `${id}.yaml`), yaml, "utf8");
    roster.push({ id, role: archetype.role });
  }

  const manifestPath = path.join(OUTPUT_DIR, "..", "shared", "metropolis-roster.js");
  const manifestBody = `// Auto-generated by scripts/generate-metropolis-npcs.js -- do not edit by hand.
// The bounded set of real, backend NpcAgent archetypes that the ambient instanced crowd
// in metropolis.html shares. Each of the hundreds of visible crowd figures is tagged with
// one of these archetype ids at spawn (see game-engine.js addCrowd); clicking/talking to
// any figure calls /ask against its archetype's single shared NpcAgent, so the number of
// real backend agents stays fixed at roster.length regardless of how large the crowd is.
window.GAMERAG_METROPOLIS_ROSTER = ${JSON.stringify(roster, null, 2)};
`;
  fs.writeFileSync(manifestPath, manifestBody, "utf8");

  console.log(`Generated ${roster.length} archetype NPC configs in ${OUTPUT_DIR}`);
  console.log(`Wrote roster manifest to ${manifestPath}`);
}

generate();
